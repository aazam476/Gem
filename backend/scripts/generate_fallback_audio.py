"""Pre-generate the fixed voice lines with ElevenLabs and bundle them in the app.

The app plays these from local files, so it can still speak when the network (and
therefore ElevenLabs) is unreachable. Without them it uses on-device speech.

    cd backend && python scripts/generate_fallback_audio.py
Writes mobile/assets/audio/<line_id>.mp3 and mobile/src/services/fallbackAudio.generated.ts
"""

from __future__ import annotations

import asyncio
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from app.config import load_settings  # noqa: E402
from app.voice import ElevenLabsVoice  # noqa: E402
from app.voice_lines import VOICE_LINES  # noqa: E402

AUDIO_DIR = ROOT / "mobile" / "assets" / "audio"
MODULE = ROOT / "mobile" / "src" / "services" / "fallbackAudio.generated.ts"


async def main() -> None:
    settings = load_settings()
    if not settings.elevenlabs_api_key:
        raise SystemExit("Set ELEVENLABS_API_KEY in backend/.env first.")
    voice = ElevenLabsVoice(settings)
    AUDIO_DIR.mkdir(parents=True, exist_ok=True)
    for line_id, text in VOICE_LINES.items():
        audio = await voice.synthesize(text)
        (AUDIO_DIR / f"{line_id}.mp3").write_bytes(audio)
        print(f"  {line_id}.mp3  {len(audio):>7} bytes")
    entries = "\n".join(
        f"  {line_id}: require('../../assets/audio/{line_id}.mp3')," for line_id in VOICE_LINES
    )
    MODULE.write_text(
        "// Generated by backend/scripts/generate_fallback_audio.py. Do not edit.\n"
        "export const FALLBACK_AUDIO: Record<string, number> = {\n" + entries + "\n};\n"
    )
    print(f"wrote {MODULE.relative_to(ROOT)}")


if __name__ == "__main__":
    asyncio.run(main())
